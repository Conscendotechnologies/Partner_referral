// Builds TEST-CASES.md: every designed test case (all levels) with its Jira key, suite and Playwright spec.
//
//   node scripts/build-index.mjs
//
// Sources: ../.specify/specs/<feature>/tests/story_NN.tc.json (the design), .../jira-map.json, test-cases/*.yaml
// (SF AI Tester suites) and tests/sf-ai/*.spec.ts (generated specs). Re-run after adding cases or specs.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const specsRoot = '../.specify/specs';
const suiteDir = 'test-cases';
const specDir = 'tests/sf-ai';
const expectedFail = JSON.parse(readFileSync('expected-failures.json', 'utf8'));

const suites = readdirSync(suiteDir).filter((f) => f.endsWith('.sf-tests.yaml'));
const suiteText = Object.fromEntries(suites.map((f) => [f, readFileSync(join(suiteDir, f), 'utf8')]));
const specs = new Set(existsSync(specDir) ? readdirSync(specDir).map((f) => f.replace(/\.spec\.ts$/, '')) : []);

const lines = [
  '# Test cases',
  '',
  'Generated by `node scripts/build-index.mjs`. Every designed test case, at every level. `ui` cases are SF AI Tester',
  'suites in `test-cases/` with a Playwright spec in `tests/sf-ai/`; `unit` cases are Apex tests in `force-app`;',
  '`manual` cases are scripts in `.specify/specs/<feature>/task_story_NN_test_scripts.md`.',
  ''
];
let totals = { all: 0, ui: 0, unit: 0, manual: 0, specs: 0 };

for (const feature of readdirSync(specsRoot).sort()) {
  const testsDir = join(specsRoot, feature, 'tests');
  if (!existsSync(testsDir)) continue;
  const mapFile = join(specsRoot, feature, 'jira-map.json');
  const map = existsSync(mapFile) ? JSON.parse(readFileSync(mapFile, 'utf8')) : { stories: {}, tests: {} };
  lines.push(`## ${feature}`, '');
  for (const f of readdirSync(testsDir).filter((x) => x.endsWith('.tc.json')).sort()) {
    const story = JSON.parse(readFileSync(join(testsDir, f), 'utf8'));
    const storyKey = (map.stories || {})[story.story] || '';
    lines.push(`### S${story.story} ${story.title}${storyKey ? ` (${storyKey})` : ''}`, '');
    lines.push('| TC | Level | AC | Persona | Title | Jira | Automation |', '|---|---|---|---|---|---|---|');
    for (const c of story.cases) {
      totals.all++;
      totals[c.level] = (totals[c.level] || 0) + 1;
      let auto = '';
      if (c.level === 'ui') {
        const suite = suites.find((s) => suiteText[s].includes(`id: ${c.id}\n`) || suiteText[s].includes(`id: ${c.id}\r\n`));
        const hasSpec = specs.has(c.id);
        if (hasSpec) totals.specs++;
        auto = [suite ? `suite \`${suite}\`` : 'no suite', hasSpec ? `spec \`${c.id}.spec.ts\`` : 'no spec yet']
          .concat(expectedFail[c.id] ? [`expected to fail until ${expectedFail[c.id]}`] : [])
          .join(', ');
      } else if (c.level === 'unit') auto = 'Apex test';
      else auto = 'manual script';
      lines.push(`| ${c.id} | ${c.level} | ${c.ac} | ${c.persona} | ${c.title.replace(/\|/g, '/')} | ${(map.tests || {})[c.id] || ''} | ${auto} |`);
    }
    lines.push('');
  }
}

lines.splice(6, 0, `**${totals.all} test cases:** ${totals.ui} ui (${totals.specs} with a Playwright spec), ${totals.unit} unit, ${totals.manual} manual.`, '');
writeFileSync('TEST-CASES.md', lines.join('\n'));
console.log(`TEST-CASES.md: ${totals.all} cases, ${totals.ui} ui, ${totals.specs} specs`);
